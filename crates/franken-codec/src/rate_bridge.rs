//! The 44.1 kHz -> 48 kHz rate bridge (`S02` / `ffw-6dh`).
//!
//! A native 44.1 kHz source (Spotify, AirPlay ALAC/AAC at 44.1 kHz) reaches the 48 kHz group domain only through this module. The ratio
//! 48 000 / 44 100 is exactly 160 / 147, so the converter is a rational polyphase FIR (up 160, filter, down 147) with no clock estimate in it.
//! D03's drift resampler (+-500 ppm, hard ceiling 10 000 ppm) is a different stage and runs after this one in the 48 kHz domain; it is NOT a
//! rate converter (160/147 is 88 435 ppm).
//!
//! # Arithmetic
//!
//! Integer only. Samples are `i32` in Q23 (a full-scale 24-bit value; a 16-bit sample is `s16 << 8`), coefficients are Q30 `i32`
//! ([`crate::rate_table`], generated by `tests/s02/gen_rate_table.py`), the accumulator is `i64`, and the result is rounded half up
//! (`(acc + 2^29) >> 30`) and clamped to the Q23 range. Integer arithmetic is the point: the PowerPC device CPU has no FPU, and an integer
//! multiply-accumulate is also exactly reproducible by the independent Python reference (`tests/s02/bridge_reference.py`), so the vectors
//! are compared bit for bit, not within a tolerance.
//!
//! # Stated cost and delay (counted, not measured)
//!
//! * `TAPS` (64) multiply-accumulates per output sample, so `64 * channels` per output frame; [`RateBridge::stats`] counts them.
//! * Group delay: exactly `TAPS / 2` = 32 input frames (725.6 us at 44.1 kHz) plus the sub-frame phase of the first output. A presentation
//!   mapping must add [`BRIDGE_DELAY_IN_FRAMES`] input frames of delay for the bridged path.
//! * The very first output frames are the filter's start-up response to silence before the first input frame (history is zero).
//! * After `n` input frames the bridge has produced exactly `ceil(160 n / 147)` output frames, whatever the chunking.
//! * [`RateBridge::flush`] pushes `TAPS` zero frames so the filter tail is delivered; it is for end of stream.
//!
//! Nothing here is a CPU, heap or stack measurement on a device. Host tests count operations and bytes only.

use crate::rate_table::{COEFF_BITS, COEFFS, DOWN, TAPS, UP};

/// The only rate that is bridged.
pub const BRIDGE_IN_RATE_HZ: u32 = 44_100;
/// The group-domain baseline rate: also the only rate that passes straight through.
pub const BRIDGE_OUT_RATE_HZ: u32 = 48_000;
/// Interpolation factor.
pub const BRIDGE_UP: usize = UP;
/// Decimation factor.
pub const BRIDGE_DOWN: usize = DOWN;
/// Taps per polyphase branch.
pub const BRIDGE_TAPS: usize = TAPS;
/// Group delay in input frames.
pub const BRIDGE_DELAY_IN_FRAMES: usize = TAPS / 2;
/// The bridge handles mono or stereo.
pub const MAX_BRIDGE_CHANNELS: usize = 2;
/// Largest Q23 value.
pub const Q23_MAX: i32 = 8_388_607;
/// Smallest Q23 value.
pub const Q23_MIN: i32 = -8_388_608;

const HALF: i64 = 1 << (COEFF_BITS - 1);
const RING_LEN: usize = TAPS * MAX_BRIDGE_CHANNELS;
const RING_MASK: usize = TAPS - 1;

/// What the source rate requires.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RatePlan {
    /// 48 kHz: no conversion.
    Direct,
    /// 44.1 kHz: the 160/147 bridge.
    Bridge,
}

/// Explicit refusals of the rate stage.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum RateError {
    /// Any rate other than 44 100 and 48 000 (88 200 and 96 000 are admitted by the control layer but not negotiated by either pin).
    #[error(
        "unsupported source rate {rate_hz} Hz: 44100 is bridged, 48000 passes through, nothing else is admitted"
    )]
    UnsupportedRate {
        /// The refused rate.
        rate_hz: u32,
    },
    /// Zero or more than [`MAX_BRIDGE_CHANNELS`] channels.
    #[error("unsupported channel count {channels}: the rate stage carries 1 or 2")]
    UnsupportedChannels {
        /// The refused count.
        channels: usize,
    },
    /// An interleaved buffer that is not a whole number of frames.
    #[error("input of {len} samples is not a whole number of {channels}-channel frames")]
    RaggedInput {
        /// Samples given.
        len: usize,
        /// Channels expected.
        channels: usize,
    },
    /// The caller's output buffer cannot hold what this call would produce; nothing was consumed.
    #[error("output holds {have} samples but this call produces {need}")]
    OutputTooSmall {
        /// Samples the buffer holds.
        have: usize,
        /// Samples this call needs.
        need: usize,
    },
}

/// Decide what a source rate needs, or refuse it.
///
/// # Errors
///
/// [`RateError::UnsupportedRate`] for every rate except 44 100 and 48 000.
pub const fn plan_for_rate(rate_hz: u32) -> Result<RatePlan, RateError> {
    match rate_hz {
        BRIDGE_OUT_RATE_HZ => Ok(RatePlan::Direct),
        BRIDGE_IN_RATE_HZ => Ok(RatePlan::Bridge),
        _ => Err(RateError::UnsupportedRate { rate_hz }),
    }
}

/// Output frames produced after exactly `in_frames` input frames: `ceil(160 * in_frames / 147)`.
#[must_use]
pub const fn outputs_after(in_frames: u64) -> u64 {
    (in_frames * UP as u64).div_ceil(DOWN as u64)
}

/// A full-scale `f32` sample to Q23: round half away from zero, clamp, NaN to 0.
#[must_use]
pub fn f32_to_q23(x: f32) -> i32 {
    let v = (x * 8_388_608.0).round();
    if v >= 8_388_607.0 {
        Q23_MAX
    } else if v <= -8_388_608.0 {
        Q23_MIN
    } else {
        // In range, so the cast is exact; NaN fails both comparisons and the saturating cast gives 0.
        v as i32
    }
}

/// A Q23 sample to a full-scale `f32` (exact: 24 bits fit an `f32` mantissa and the divisor is a power of two).
#[must_use]
pub fn q23_to_f32(v: i32) -> f32 {
    v as f32 / 8_388_608.0
}

/// A 16-bit sample to Q23.
#[must_use]
pub const fn s16_to_q23(v: i16) -> i32 {
    (v as i32) << 8
}

/// A Q23 sample to 16 bits: round half up, clamp.
#[must_use]
pub fn q23_to_s16(v: i32) -> i16 {
    let r = (i64::from(v) + 128) >> 8;
    r.clamp(i64::from(i16::MIN), i64::from(i16::MAX)) as i16
}

/// Frames consumed and produced by one call.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct BridgeCounts {
    /// Input frames consumed.
    pub in_frames: usize,
    /// Output frames produced.
    pub out_frames: usize,
}

/// Counters since construction or the last [`RateBridge::reset`].
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct BridgeStats {
    /// Input frames consumed.
    pub in_frames: u64,
    /// Output frames produced.
    pub out_frames: u64,
    /// Multiply-accumulates performed.
    pub macs: u64,
    /// Output samples that hit the Q23 clamp.
    pub clipped: u64,
}

/// The 160/147 polyphase converter. Fixed storage, no allocation after construction.
#[derive(Debug, Clone)]
pub struct RateBridge {
    channels: usize,
    ring: [i32; RING_LEN],
    /// Input index of the newest input frame the next output needs.
    m: u64,
    /// Polyphase branch of the next output, `(n * 147) mod 160`.
    r: usize,
    stats: BridgeStats,
}

impl RateBridge {
    /// A bridge for 1 or 2 interleaved channels.
    ///
    /// # Errors
    ///
    /// [`RateError::UnsupportedChannels`] for any other count.
    pub fn new(channels: usize) -> Result<Self, RateError> {
        if channels == 0 || channels > MAX_BRIDGE_CHANNELS {
            return Err(RateError::UnsupportedChannels { channels });
        }
        Ok(Self {
            channels,
            ring: [0; RING_LEN],
            m: 0,
            r: 0,
            stats: BridgeStats::default(),
        })
    }

    /// Channels per frame.
    #[must_use]
    pub const fn channels(&self) -> usize {
        self.channels
    }

    /// Counters since construction or the last reset.
    #[must_use]
    pub const fn stats(&self) -> BridgeStats {
        self.stats
    }

    /// Multiply-accumulates per output frame: `TAPS * channels`.
    #[must_use]
    pub const fn macs_per_output_frame(&self) -> usize {
        TAPS * self.channels
    }

    /// Back to the state of a new bridge (zero history, counters zero). Use after a seek or a format change.
    pub fn reset(&mut self) {
        self.ring = [0; RING_LEN];
        self.m = 0;
        self.r = 0;
        self.stats = BridgeStats::default();
    }

    /// Output samples (frames times channels) that consuming `in_frames` more input frames produces.
    #[must_use]
    pub fn output_samples_for(&self, in_frames: usize) -> usize {
        let before = outputs_after(self.stats.in_frames);
        let after = outputs_after(self.stats.in_frames + in_frames as u64);
        (after - before) as usize * self.channels
    }

    /// Output samples that [`RateBridge::flush`] produces.
    #[must_use]
    pub fn flush_output_samples(&self) -> usize {
        self.output_samples_for(TAPS)
    }

    /// Consume every frame of `input` (interleaved Q23) and write the produced frames to `output`.
    ///
    /// The output is independent of how the input is split across calls. If `output` is too small nothing is consumed.
    ///
    /// # Errors
    ///
    /// [`RateError::RaggedInput`] or [`RateError::OutputTooSmall`].
    pub fn process(
        &mut self,
        input: &[i32],
        output: &mut [i32],
    ) -> Result<BridgeCounts, RateError> {
        let ch = self.channels;
        if !input.len().is_multiple_of(ch) {
            return Err(RateError::RaggedInput {
                len: input.len(),
                channels: ch,
            });
        }
        let frames = input.len() / ch;
        let need = self.output_samples_for(frames);
        if output.len() < need {
            return Err(RateError::OutputTooSmall {
                have: output.len(),
                need,
            });
        }
        let mut produced = 0usize;
        for frame in input.chunks_exact(ch) {
            let j = self.stats.in_frames;
            let slot = ((j as usize) & RING_MASK) * ch;
            self.ring[slot..slot + ch].copy_from_slice(frame);
            self.stats.in_frames += 1;
            // Every input frame yields one or two outputs, because 160/147 > 1 and a branch advance is at most one input frame.
            while self.m == j {
                let dst = &mut output[produced * ch..(produced + 1) * ch];
                let clipped = self.emit(dst);
                self.stats.clipped += clipped;
                self.stats.macs += (TAPS * ch) as u64;
                self.stats.out_frames += 1;
                produced += 1;
                self.r += DOWN;
                if self.r >= UP {
                    self.r -= UP;
                    self.m += 1;
                }
            }
        }
        debug_assert_eq!(produced * ch, need);
        Ok(BridgeCounts {
            in_frames: frames,
            out_frames: produced,
        })
    }

    /// Push `TAPS` zero frames so the filter tail is delivered. For end of stream; call [`RateBridge::reset`] to reuse the bridge.
    ///
    /// # Errors
    ///
    /// [`RateError::OutputTooSmall`] (nothing consumed).
    pub fn flush(&mut self, output: &mut [i32]) -> Result<BridgeCounts, RateError> {
        let zeros = [0i32; RING_LEN];
        let n = TAPS * self.channels;
        self.process(&zeros[..n], output)
    }

    /// One output frame for the current `(m, r)`: `y = sum_k COEFFS[r][k] * x[m - k]`, rounded and clamped. Returns the clamp count.
    fn emit(&self, dst: &mut [i32]) -> u64 {
        let ch = self.channels;
        let phase = &COEFFS[self.r * TAPS..(self.r + 1) * TAPS];
        let mut clipped = 0u64;
        for (c, out) in dst.iter_mut().enumerate() {
            let mut acc: i64 = 0;
            for (k, &coef) in phase.iter().enumerate() {
                // `m - k` below zero wraps to a ring slot that has not been written yet, which still holds the initial zero.
                let idx = ((self.m.wrapping_sub(k as u64) as usize) & RING_MASK) * ch + c;
                acc += i64::from(coef) * i64::from(self.ring[idx]);
            }
            let rounded = (acc + HALF) >> COEFF_BITS;
            *out = if rounded > i64::from(Q23_MAX) {
                clipped += 1;
                Q23_MAX
            } else if rounded < i64::from(Q23_MIN) {
                clipped += 1;
                Q23_MIN
            } else {
                rounded as i32
            };
        }
        clipped
    }
}

/// Native-rate decoder output to 48 kHz Q23: pass-through at 48 kHz, the bridge at 44.1 kHz, a refusal otherwise.
///
/// This is where a decoded block's `rate_hz` is checked, so a rate cannot be lost or silently reinterpreted between crates.
#[derive(Debug, Clone)]
pub struct RateAdapter {
    rate_hz: u32,
    channels: usize,
    bridge: Option<RateBridge>,
    scratch: Vec<i32>,
}

impl RateAdapter {
    /// An adapter for a source of `rate_hz` and `channels`.
    ///
    /// # Errors
    ///
    /// [`RateError::UnsupportedRate`] or [`RateError::UnsupportedChannels`].
    pub fn new(rate_hz: u32, channels: usize) -> Result<Self, RateError> {
        let plan = plan_for_rate(rate_hz)?;
        if channels == 0 || channels > MAX_BRIDGE_CHANNELS {
            return Err(RateError::UnsupportedChannels { channels });
        }
        let bridge = match plan {
            RatePlan::Direct => None,
            RatePlan::Bridge => Some(RateBridge::new(channels)?),
        };
        Ok(Self {
            rate_hz,
            channels,
            bridge,
            scratch: Vec::new(),
        })
    }

    /// What this adapter does.
    #[must_use]
    pub const fn plan(&self) -> RatePlan {
        if self.bridge.is_some() {
            RatePlan::Bridge
        } else {
            RatePlan::Direct
        }
    }

    /// The source rate this adapter was built for.
    #[must_use]
    pub const fn source_rate_hz(&self) -> u32 {
        self.rate_hz
    }

    /// Channels per frame.
    #[must_use]
    pub const fn channels(&self) -> usize {
        self.channels
    }

    /// Counters of the bridge (all zero for a pass-through adapter).
    #[must_use]
    pub fn stats(&self) -> BridgeStats {
        self.bridge
            .as_ref()
            .map(RateBridge::stats)
            .unwrap_or_default()
    }

    /// Clear the filter history (after a seek or a format change).
    pub fn reset(&mut self) {
        if let Some(bridge) = self.bridge.as_mut() {
            bridge.reset();
        }
    }

    /// Convert an interleaved `f32` block to 48 kHz Q23. `out` is replaced.
    ///
    /// # Errors
    ///
    /// [`RateError::RaggedInput`] when `input` is not a whole number of frames.
    pub fn process_f32(&mut self, input: &[f32], out: &mut Vec<i32>) -> Result<(), RateError> {
        let ch = self.channels;
        if !input.len().is_multiple_of(ch) {
            return Err(RateError::RaggedInput {
                len: input.len(),
                channels: ch,
            });
        }
        out.clear();
        match self.bridge.as_mut() {
            None => {
                out.extend(input.iter().map(|&x| f32_to_q23(x)));
                Ok(())
            }
            Some(bridge) => {
                self.scratch.clear();
                self.scratch.extend(input.iter().map(|&x| f32_to_q23(x)));
                out.resize(bridge.output_samples_for(self.scratch.len() / ch), 0);
                bridge.process(&self.scratch, out)?;
                Ok(())
            }
        }
    }

    /// Deliver the filter tail at end of stream (nothing for a pass-through adapter). `out` is replaced.
    ///
    /// # Errors
    ///
    /// Never in practice (the buffer is sized here); the type is shared with [`RateBridge::flush`].
    pub fn flush(&mut self, out: &mut Vec<i32>) -> Result<(), RateError> {
        out.clear();
        if let Some(bridge) = self.bridge.as_mut() {
            out.resize(bridge.flush_output_samples(), 0);
            bridge.flush(out)?;
        }
        Ok(())
    }
}
