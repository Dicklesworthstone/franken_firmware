#!/usr/bin/env python3
"""P02 (ffw-jub): the harness-guest capability evidence compiled into the device speaker is the evidence E03 committed.

`crates/franken-speaker/src/guest_evidence.rs` is generated by `scripts/p02/gen_guest_evidence.py` from the committed serial
transcripts through the E03 oracle. These tests hold the committed file to a fresh generation (drift), to the oracle's own
statuses read independently of the generator's renderer, and to the transcripts' SHA-256; and they plant bad evidence (a failing
probe, a non-matching kernel, a missing resolution, a mislocated UNSEEDED) and require the generator to refuse or to change its
output, so a generator that always emits cannot pass. Offline, stdlib only; no cargo, no QEMU.
"""
import hashlib
import importlib.util
import os
import re
import sys
import unittest

ROOT = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
GENERATOR = os.path.join(ROOT, "scripts", "p02", "gen_guest_evidence.py")
EVIDENCE_RS = os.path.join(ROOT, "crates", "franken-speaker", "src", "guest_evidence.rs")
RUN = os.path.join(ROOT, "toolchain", "results", "runs", "1412ac47120d4e5b865f9de6e05f50fe")
LOGS = {"HARNESS_PPC": "boot-ppc-serial.log", "HARNESS_MIPS": "boot-mips-serial.log"}
PROFILES = {"HARNESS_PPC": "harness-ppc-4.9", "HARNESS_MIPS": "harness-mips-4.19"}


def load_generator():
    spec = importlib.util.spec_from_file_location("ffw_p02_gen_guest_evidence", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    sys.modules["ffw_p02_gen_guest_evidence"] = module
    spec.loader.exec_module(module)
    return module


def read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def static_fields(source, name):
    """{field: value} of `pub static <name>: GuestEvidence = GuestEvidence { ... };` in the committed Rust."""
    match = re.search(r"pub static %s: GuestEvidence = GuestEvidence \{(.*?)\n\};" % re.escape(name), source, re.S)
    if not match:
        raise AssertionError("no static named %s" % name)
    fields = {}
    for key, value in re.findall(r"^\s+([a-z0-9_]+): (.+),$", match.group(1), re.M):
        if key in fields:
            raise AssertionError("%s sets %s twice" % (name, key))
        fields[key] = value.strip().strip('"')
    return fields


class GeneratedFileTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.gen = load_generator()
        cls.source = read(EVIDENCE_RS)

    def test_the_committed_file_is_what_the_transcripts_generate(self):
        self.assertEqual(self.gen.generate(), self.source, "run scripts/p02/gen_guest_evidence.py --write")
        self.assertEqual(self.gen.main([]), 0)

    def test_every_status_equals_the_oracles_and_only_getrandom_on_mips_is_unseeded(self):
        oracle = self.gen.load_oracle()
        for name, log in LOGS.items():
            facts = self.gen.derive(oracle, PROFILES[name], read(os.path.join(RUN, log)))
            fields = static_fields(self.source, name)
            for field, variant in facts["statuses"].items():
                self.assertEqual(fields[field], "CapabilityStatus::" + variant, "%s.%s" % (name, field))
            self.assertEqual(fields["kernel_release"], facts["kernel_release"], name)
            self.assertEqual(fields["target_triple"], facts["target_triple"], name)
            self.assertEqual(fields["clock_monotonic_res_ns"], str(facts["resolution_ns"]), name)
            self.assertEqual(fields["static_elf_startup"], "CapabilityStatus::Supported", name)
        ppc, mips = (static_fields(self.source, n) for n in ("HARNESS_PPC", "HARNESS_MIPS"))
        self.assertEqual(ppc["getrandom_syscall"], "CapabilityStatus::Supported")
        self.assertEqual(mips["getrandom_syscall"], "CapabilityStatus::ObservedUnseeded")
        for field, value in {**ppc, **mips}.items():
            if field.endswith(("_syscall", "_io", "_entropy", "_32bit", "_fallback", "_monotonic", "_startup")) and field != "getrandom_syscall":
                self.assertEqual(value, "CapabilityStatus::Supported", field)

    def test_the_run_id_and_transcript_digests_are_the_committed_logs(self):
        for name, log in LOGS.items():
            fields = static_fields(self.source, name)
            with open(os.path.join(RUN, log), "rb") as fh:
                self.assertEqual(fields["transcript_sha256"], hashlib.sha256(fh.read()).hexdigest(), name)
            self.assertEqual(fields["run_id"], os.path.basename(RUN), name)

    def test_the_generated_file_names_no_absolute_path_and_no_user(self):
        for needle in ("/Users/", "/private/", "/home/", "/tmp/", "jemanuel"):
            self.assertNotIn(needle, self.source, needle)

    def test_the_two_guests_are_the_two_harness_kernels_and_the_abis_are_distinct(self):
        ppc, mips = (static_fields(self.source, n) for n in ("HARNESS_PPC", "HARNESS_MIPS"))
        self.assertEqual(ppc["kernel_release"], "4.9.0-0.bpo.6-powerpc")
        self.assertEqual(mips["kernel_release"], "4.19.0-21-4kc-malta")
        self.assertEqual((ppc["abi"], mips["abi"]), ("Abi::PowerPc32", "Abi::Mips32"))
        self.assertEqual((ppc["target_triple"], mips["target_triple"]), ("powerpc-unknown-linux-musl", "mips-unknown-linux-musl"))
        self.assertIn("match abi {\n        Abi::PowerPc32 => &HARNESS_PPC,\n        Abi::Mips32 => &HARNESS_MIPS,", self.source)


class PlantedEvidenceTests(unittest.TestCase):
    """Bad evidence must be refused, or must change the output. Each plant is removed by the baseline test above passing."""

    @classmethod
    def setUpClass(cls):
        cls.gen = load_generator()
        cls.oracle = cls.gen.load_oracle()
        cls.ppc = read(os.path.join(RUN, LOGS["HARNESS_PPC"]))
        cls.mips = read(os.path.join(RUN, LOGS["HARNESS_MIPS"]))

    def test_the_unplanted_transcripts_derive(self):
        self.gen.derive(self.oracle, "harness-ppc-4.9", self.ppc)
        self.gen.derive(self.oracle, "harness-mips-4.19", self.mips)

    def test_a_failing_probe_is_refused(self):
        bad = self.ppc.replace("FFW_PROBE:EVENTFD2 status=PASS", "FFW_PROBE:EVENTFD2 status=FAIL", 1)
        self.assertNotEqual(bad, self.ppc)
        with self.assertRaises(self.gen.EvidenceError):
            self.gen.derive(self.oracle, "harness-ppc-4.9", bad)

    def test_a_kernel_that_is_not_the_profiles_is_refused(self):
        # The PPC harness transcript judged against the stock 2.6.14 profile is not matching-guest evidence.
        with self.assertRaises(self.gen.EvidenceError):
            self.gen.derive(self.oracle, "stock-ppc-2.6.14", self.ppc)
        with self.assertRaises(self.gen.EvidenceError):
            self.gen.derive(self.oracle, "harness-ppc-4.9", self.mips)

    def test_a_missing_or_absurd_clock_resolution_is_refused(self):
        gone = re.sub(r"FFW_PROBE:CLOCK_MONOTONIC status=PASS res_ns=\d+", "FFW_PROBE:CLOCK_MONOTONIC status=PASS", self.ppc, count=1)
        self.assertNotEqual(gone, self.ppc)
        with self.assertRaises(self.gen.EvidenceError):
            self.gen.derive(self.oracle, "harness-ppc-4.9", gone)

    def test_unseeded_on_ppc_getrandom_changes_the_output_and_on_any_other_probe_is_refused(self):
        seeded = self.gen.derive(self.oracle, "harness-ppc-4.9", self.ppc)
        unseeded = self.ppc.replace("FFW_PROBE:GETRANDOM status=PASS rc=16", "FFW_PROBE:GETRANDOM status=UNSEEDED rc=-11", 1)
        self.assertNotEqual(unseeded, self.ppc)
        derived = self.gen.derive(self.oracle, "harness-ppc-4.9", unseeded)
        self.assertEqual(seeded["statuses"]["getrandom_syscall"], "Supported")
        self.assertEqual(derived["statuses"]["getrandom_syscall"], "ObservedUnseeded")
        misplaced = self.ppc.replace("FFW_PROBE:EVENTFD2 status=PASS fd=4", "FFW_PROBE:EVENTFD2 status=UNSEEDED rc=-11", 1)
        self.assertNotEqual(misplaced, self.ppc)
        with self.assertRaises(self.gen.EvidenceError):
            self.gen.derive(self.oracle, "harness-ppc-4.9", misplaced)

    def test_the_oracle_calls_the_mips_guest_degraded_and_the_ppc_guest_green(self):
        self.assertEqual(self.gen.derive(self.oracle, "harness-ppc-4.9", self.ppc)["verdict"], "green")
        self.assertEqual(self.gen.derive(self.oracle, "harness-mips-4.19", self.mips)["verdict"], "degraded")


if __name__ == "__main__":
    unittest.main()
