#!/usr/bin/env python3
"""Generate the 160/147 polyphase coefficient table for `crates/franken-codec/src/rate_table.rs` (S02 / ffw-6dh). Stdlib only.

Design (every number is a written constant below, not a tuning result):

* The bridge converts 44 100 Hz to 48 000 Hz. 48 000 / 44 100 = 160 / 147 exactly, so the converter is a rational one: up by L = 160, filter,
  down by M = 147. There is no clock estimate in it and no drift term (D03's +-ppm stage is a different thing and stays after this one).
* The prototype lowpass is a Kaiser-windowed sinc of N = K * L = 64 * 160 = 10 240 taps designed at the up-sampled rate 44 100 * 160 = 7 056 000 Hz.
  Its centre is tap N / 2 (the window is symmetric about it, tap 0 is the window's tiny edge value), so the group delay is exactly
  N / 2 up-sampled samples = K / 2 = 32 input frames.
* Kaiser beta = 6.75566 is the Kaiser formula 0.1102 * (A - 8.7) for A = 70 dB of stop-band attenuation. The formula's transition width
  for N = 10 240 and A = 70 dB is 2 979 Hz, so a cut-off of 20 560 Hz puts the pass-band edge near 19 070 Hz and the stop-band edge at the input
  Nyquist 22 050 Hz. These are design intents; the MEASURED response of the integer table is what tests/s02/bridge_reference.py checks.
* Phase r (0..159) uses taps h[160 * k + r], k = 0..63. Each phase is scaled so its coefficients sum to EXACTLY 2^30 (Q30): the rounding residual
  is added to that phase's largest coefficient. So the DC gain is exactly 1 at every phase, with no phase-dependent amplitude modulation, and a
  constant input c gives exactly c at the output once the history is full. That exactness is a test, not a hope.
* Coefficients are stored phase-major: COEFFS[r * 64 + k]. The largest coefficient is about 1.0 (Q30 ~ 2^30), so every one fits an i32.

    gen_rate_table.py --write PATH     write the Rust file
    gen_rate_table.py --check PATH     exit 0 only when PATH equals a fresh generation byte for byte
    gen_rate_table.py --summary        print the design numbers and the phase-sum residuals
"""
from __future__ import annotations

import argparse
import hashlib
import math
import sys

L = 160
M = 147
K = 64
N = K * L
IN_RATE = 44_100
FS_UP = IN_RATE * L
FC_HZ = 20_560.0
BETA = 6.75566
Q = 30
ONE = 1 << Q


def i0(x: float) -> float:
    term = 1.0
    total = 1.0
    k = 1
    while True:
        term *= (x / (2.0 * k)) ** 2
        total += term
        if term < total * 1e-17:
            return total
        k += 1


def prototype() -> list:
    wc = 2.0 * math.pi * FC_HZ / FS_UP
    centre = N // 2
    i0b = i0(BETA)
    h = []
    for n in range(N):
        m = n - centre
        ideal = wc / math.pi if m == 0 else math.sin(wc * m) / (math.pi * m)
        arg = 1.0 - (m / centre) ** 2
        window = i0(BETA * math.sqrt(arg if arg > 0.0 else 0.0)) / i0b
        h.append(L * ideal * window)
    return h


def table() -> tuple:
    h = prototype()
    coeffs = []
    residuals = []
    float_sums = []
    for r in range(L):
        phase = [h[L * k + r] for k in range(K)]
        float_sums.append(sum(phase))
        q = [int(round(v * ONE)) for v in phase]
        residual = ONE - sum(q)
        big = max(range(K), key=lambda i: (abs(q[i]), -i))
        q[big] += residual
        residuals.append(residual)
        assert sum(q) == ONE
        assert all(-(1 << 31) <= v < (1 << 31) for v in q)
        coeffs.extend(q)
    return coeffs, residuals, float_sums


def render(coeffs: list) -> str:
    digest = hashlib.sha256((",".join(str(c) for c in coeffs)).encode("ascii")).hexdigest()
    out = []
    out.append("// GENERATED by tests/s02/gen_rate_table.py. Do not edit by hand: `gen_rate_table.py --check` must reproduce this file byte for byte.")
    out.append("//")
    out.append("// 160/147 polyphase table, Q30, phase-major (`COEFFS[phase * TAPS + tap]`). Design and the reasons for every constant are in the generator's header.")
    out.append(f"// sha256 of the comma-joined decimal values: {digest}")
    out.append("")
    out.append(f"pub(crate) const UP: usize = {L};")
    out.append(f"pub(crate) const DOWN: usize = {M};")
    out.append(f"pub(crate) const TAPS: usize = {K};")
    out.append(f"pub(crate) const COEFF_BITS: u32 = {Q};")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"pub(crate) static COEFFS: [i32; {L * K}] = [")
    for i in range(0, len(coeffs), 8):
        out.append("    " + ", ".join(str(c) for c in coeffs[i:i + 8]) + ",")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write")
    g.add_argument("--check")
    g.add_argument("--summary", action="store_true")
    args = ap.parse_args()
    coeffs, residuals, float_sums = table()
    if args.summary:
        print(f"L={L} M={M} K={K} N={N} fs_up={FS_UP} fc={FC_HZ} beta={BETA} Q={Q}")
        print(f"max |phase-sum residual before fix| = {max(abs(r) for r in residuals)} LSB of Q30")
        print(f"float phase sums: min={min(float_sums):.9f} max={max(float_sums):.9f}")
        print(f"max coeff = {max(coeffs)} ({max(coeffs) / ONE:.6f}), min coeff = {min(coeffs)} ({min(coeffs) / ONE:.6f})")
        return 0
    text = render(coeffs)
    if args.write:
        with open(args.write, "w", encoding="ascii", newline="\n") as f:
            f.write(text)
        print(f"wrote {args.write} ({len(text)} bytes)")
        return 0
    with open(args.check, encoding="ascii") as f:
        have = f.read()
    if have != text:
        print("DIFFERENT from a fresh generation", file=sys.stderr)
        return 1
    print("identical to a fresh generation")
    return 0


if __name__ == "__main__":
    sys.exit(main())
