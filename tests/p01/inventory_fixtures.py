"""Synthetic worlds for the E06-inventory cases (P01-INV-*): a lockfile and an `ffw.e06.audit.v1` record made FROM it, which agree.
A plant changes exactly one thing and names the verdict and the finding codes `inventory.judge` must then report, written out by
hand from the rules in inventory.py. Nothing here reads the real Cargo.lock or the real audit: the permitted positives and every
planted negative hold on data that exists only in this file, so the verdict cannot depend on what E06 last committed."""
from __future__ import annotations

import contextlib
import copy
import hashlib
import io
import json
import os
import tempfile
from typing import Any, Callable, Dict, List, Tuple

import inventory

REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
SUMS = {"cfg-if": "a1" * 32, "serde": "b2" * 32, "itoa": "c3" * 32}


def lock_text(extra_ws: Tuple[str, ...] = (), drop: Tuple[str, ...] = (), versions: Dict[str, str] = None,
              extra_ext: Tuple[str, ...] = (), comment: str = "") -> bytes:
    versions = versions or {}
    parts = ["# This file is automatically @generated by Cargo.\nversion = 4\n" + comment]
    for name in ("cfg-if", "itoa", "serde"):
        if name == "itoa" and "itoa" not in extra_ext:
            continue
        if name in drop:
            continue
        parts.append(f'\n[[package]]\nname = "{name}"\nversion = "{versions.get(name, "1.0.0")}"\nsource = "{REGISTRY}"\n'
                     f'checksum = "{SUMS[name]}"\n')
    for name in ("ws-app", "ws-lib") + tuple(extra_ws):
        if name in drop:
            continue
        deps = '\ndependencies = [\n "serde",\n]\n' if name == "ws-app" else "\n"
        parts.append(f'\n[[package]]\nname = "{name}"\nversion = "0.1.0"{deps}')
    return "".join(parts).encode("utf-8")


def make_audit(lock: bytes) -> Dict[str, Any]:
    """The audit E06 would write for this lock: member rows and pins per platform, a record per package, the lock's hash."""
    external, workspace, total = inventory.parse_lock(lock)
    rows: List[Dict[str, Any]] = [{"checksum": None, "features": [], "package": f"{name}@0.1.0", "role": "member", "source": "workspace"}
                                  for name in sorted(workspace)]
    rows += [{"checksum": chk, "features": ["std"], "package": key, "role": "linked", "source": src}
             for key, (src, chk) in sorted(external.items())]
    packages = [{"key": f"{n}@0.1.0", "name": n, "source_kind": "workspace", "version": "0.1.0", "unsafe": {"basis": "own-source-token-scan"},
                 "license": {"expression": "MIT", "status": "declared"}} for n in sorted(workspace)]
    packages += [{"key": key, "name": key.split("@")[0], "source_kind": "registry", "version": key.split("@")[1],
                  "unsafe": {"basis": "own-source-token-scan"}, "license": {"expression": "MIT OR Apache-2.0", "status": "declared"}}
                 for key in sorted(external)]
    return {"schema": inventory.AUDIT_SCHEMA,
            "lock": {"entries": total, "sha256": hashlib.sha256(lock).hexdigest()},
            "pins": {plat: {"digest": "0" * 64, "rows": copy.deepcopy(rows)} for plat in inventory.PLATFORMS},
            "packages": packages, "summary": {"counts": {"blocker": 0, "info": len(packages), "review": 2}}}


World = Tuple[bytes, Dict[str, Any]]


def world() -> World:
    lock = lock_text()
    return lock, make_audit(lock)


def _claims(lock: bytes, audit: Dict[str, Any]) -> Dict[str, Any]:
    """The audit edited to CLAIM `lock` without being re-made from it (the forgery the consistency checks exist for)."""
    audit = copy.deepcopy(audit)
    audit["lock"] = {"entries": inventory.parse_lock(lock)[2], "sha256": hashlib.sha256(lock).hexdigest()}
    return audit


def _each_platform(audit, edit: Callable[[List[Dict[str, Any]]], None]) -> None:
    for plat in inventory.PLATFORMS:
        edit(audit["pins"][plat]["rows"])


def _row(audit, key: str, plat: str = "host") -> Dict[str, Any]:
    return next(r for r in audit["pins"][plat]["rows"] if r["package"] == key)


def _record(audit, key: str) -> Dict[str, Any]:
    return next(p for p in audit["packages"] if p["key"] == key)


Plant = Tuple[str, str, Callable[[World], World], str, List[str]]


def _p(f: Callable[[Dict[str, Any]], None]) -> Callable[[World], World]:
    def run(w: World) -> World:
        audit = copy.deepcopy(w[1])
        f(audit)
        return w[0], audit
    return run


def _drop_serde_rows(audit):
    for plat in inventory.PLATFORMS:
        audit["pins"][plat]["rows"] = [r for r in audit["pins"][plat]["rows"] if r["package"] != "serde@1.0.0"]


def _ghost_row(audit):
    audit["pins"]["host"]["rows"].append({"checksum": "d4" * 32, "features": [], "package": "ghost@1.0.0", "role": "linked", "source": REGISTRY})


def _drop_crate_record(audit):
    audit["packages"] = [p for p in audit["packages"] if p["key"] != "ws-lib@0.1.0"]


def _ghost_crate_record(audit):
    audit["packages"].append({"key": "ws-ghost@0.1.0", "name": "ws-ghost", "source_kind": "workspace", "version": "0.1.0",
                              "unsafe": {}, "license": {}})


def _drop_pins_mips(audit):
    audit["pins"]["mips"] = {}


PLANTS: List[Plant] = [
    # ---- stale: the audit binds another lock. blocked, with the delta named
    ("stale", "a workspace crate added to the lock after the audit", lambda w: (lock_text(extra_ws=("ws-new",)), w[1]), "blocked",
     ["audit_lock_stale", "stale_workspace_crate_not_audited"]),
    ("stale", "a workspace crate removed from the lock", lambda w: (lock_text(drop=("ws-lib",)), w[1]), "blocked",
     ["audit_lock_stale", "stale_workspace_crate_removed"]),
    ("stale", "a dependency dropped from the lock", lambda w: (lock_text(drop=("cfg-if",)), w[1]), "blocked",
     ["audit_lock_stale", "stale_pin_not_in_lock"]),
    ("stale", "a dependency added to the lock", lambda w: (lock_text(extra_ext=("itoa",)), w[1]), "blocked",
     ["audit_lock_stale", "stale_lock_package_not_pinned"]),
    ("stale", "a dependency bumped to another version", lambda w: (lock_text(versions={"serde": "1.0.1"}), w[1]), "blocked",
     ["audit_lock_stale", "stale_lock_package_not_pinned", "stale_pin_not_in_lock"]),
    ("stale", "the same packages in a different file", lambda w: (lock_text(comment="# regenerated\n"), w[1]), "blocked",
     ["audit_lock_stale"]),
    # ---- inconsistent: the audit claims THIS lock and disagrees with it. fail, one code each
    ("inconsistent", "a pin whose checksum is not the lock's", _p(lambda a: _row(a, "cfg-if@1.0.0").update(checksum="e5" * 32)), "fail", ["pin_differs"]),
    ("inconsistent", "a pin whose source is not the lock's",
     _p(lambda a: _row(a, "serde@1.0.0").update(source="git+https://example.invalid/serde?rev=0")), "fail", ["pin_differs"]),
    ("inconsistent", "a locked package no platform pins", _p(_drop_serde_rows), "fail", ["lock_package_not_pinned"]),
    ("inconsistent", "a pin for a package the lock does not have", _p(_ghost_row), "fail", ["pin_not_in_lock"]),
    ("inconsistent", "a workspace crate with no record", _p(_drop_crate_record), "fail", ["crate_not_audited"]),
    ("inconsistent", "a record for a workspace crate the lock does not have", _p(_ghost_crate_record), "fail", ["audited_crate_not_in_lock"]),
    ("inconsistent", "a package record without its licence", _p(lambda a: _record(a, "serde@1.0.0").pop("license")), "fail",
     ["package_field_missing"]),
    ("inconsistent", "a package record without its unsafe fact", _p(lambda a: _record(a, "cfg-if@1.0.0").pop("unsafe")), "fail",
     ["package_field_missing"]),
    ("inconsistent", "a platform with no pins", _p(_drop_pins_mips), "fail", ["audit_shape"]),
    ("inconsistent", "an unknown schema", _p(lambda a: a.update(schema="ffw.e06.audit.v0")), "fail", ["audit_shape"]),
    ("inconsistent", "a blocker in the audit's own summary", _p(lambda a: a["summary"]["counts"].update(blocker=1)), "fail",
     ["audit_has_blockers"]),
    ("inconsistent", "the wrong lock entry count", _p(lambda a: a["lock"].update(entries=a["lock"]["entries"] + 1)), "fail",
     ["lock_entries_differs"]),
    # ---- claims_current: the audit was edited to claim the new lock without being re-made from it. A package never audited has no
    # pin AND no record, so both are reported
    ("claims_current", "a new workspace crate, the hash edited to match",
     lambda w: (lock_text(extra_ws=("ws-new",)), _claims(lock_text(extra_ws=("ws-new",)), w[1])), "fail", ["crate_not_audited"]),
    ("claims_current", "a new dependency, the hash edited to match",
     lambda w: (lock_text(extra_ext=("itoa",)), _claims(lock_text(extra_ext=("itoa",)), w[1])), "fail",
     ["lock_package_not_pinned", "package_field_missing"]),
    ("claims_current", "a bumped dependency, the hash edited to match",
     lambda w: (lock_text(versions={"serde": "1.0.1"}), _claims(lock_text(versions={"serde": "1.0.1"}), w[1])), "fail",
     ["lock_package_not_pinned", "package_field_missing", "pin_not_in_lock"]),
]
GROUPS = ("stale", "inconsistent", "claims_current")


def _host_only(audit):
    audit["pins"]["mips"]["rows"] = [r for r in audit["pins"]["mips"]["rows"] if r["package"] != "cfg-if@1.0.0"]
    audit["pins"]["powerpc"]["rows"] = [r for r in audit["pins"]["powerpc"]["rows"] if r["package"] != "cfg-if@1.0.0"]


def _reordered(audit):
    for plat in inventory.PLATFORMS:
        audit["pins"][plat]["rows"].reverse()
    audit["packages"].reverse()
    _row(audit, "serde@1.0.0", "mips")["features"] = ["default", "derive", "std"]


def _many_review(audit):
    audit["summary"]["counts"]["review"] = 14


# permitted positives: each is the same world with something that is allowed to differ
POSITIVES: List[Tuple[str, Callable[[World], World]]] = [
    ("the unaltered world", lambda w: w),
    ("a package pinned on the host only (a proc-macro or build tool)", _p(_host_only)),
    ("rows and records in another order, a package with other features per platform", _p(_reordered)),
    ("review items outstanding (human decisions, not judged here)", _p(_many_review)),
]


def _run(w: World) -> Tuple[str, List[str], str]:
    verdict, findings, detail = inventory.judge(w[1], w[0])
    return verdict, inventory.codes(findings), detail


def judge_positive() -> str:
    """Every permitted positive passes, directly and through the command line on files."""
    for label, make in POSITIVES:
        got = _run(make(world()))
        assert got[0] == "pass" and got[1] == [], f"permitted positive `{label}` is {got[0]} {got[1]}: {got[2][:160]}"
    with tempfile.TemporaryDirectory() as tmp:
        lock, audit = world()
        paths = {"audit": os.path.join(tmp, "audit.json"), "lock": os.path.join(tmp, "Cargo.lock")}
        with open(paths["audit"], "w", encoding="utf-8") as f:
            json.dump(audit, f)
        with open(paths["lock"], "wb") as f:
            f.write(lock)
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = inventory.main([paths["audit"], "--lock", paths["lock"]])
        assert code == 0, f"the command line says {code}: {out.getvalue()} {err.getvalue()}"
    return f"{len(POSITIVES)} permitted positives pass, in the library and through the command line"


def judge_group(group: str) -> str:
    """Every plant of `group` gets exactly its verdict and code set, and the unplanted control passes first."""
    assert _run(world())[0] == "pass", "the unplanted control does not pass"
    plants = [p for p in PLANTS if p[0] == group]
    assert plants, f"no plants in group {group}"
    wrong = []
    for _g, label, make, verdict, want in plants:
        got = _run(make(world()))
        if (got[0], got[1]) != (verdict, sorted(want)):
            wrong.append(f"`{label}`: {got[0]} {got[1]}, want {verdict} {sorted(want)}")
    assert not wrong, "; ".join(wrong)
    return f"{len(plants)} plants each get exactly their verdict and codes ({'/'.join(sorted({p[3] for p in plants}))}); the control passes"
